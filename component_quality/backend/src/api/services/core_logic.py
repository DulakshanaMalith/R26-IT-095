def build_analysis_history_index() -> dict[str, dict[str, Any]]:
    """Index analysis history by exact analysis_id for cross-record completeness lookups."""
    indexed: dict[str, dict[str, Any]] = {}
    for record in load_analysis_history():
        if not isinstance(record, dict):
            continue
        analysis_id = record_analysis_id(record)
        if analysis_id:
            indexed[analysis_id] = record
    return indexed


def linked_analysis_text_for_grading(
    grading_record: dict[str, Any],
    analysis_index: dict[str, dict[str, Any]] | None = None,
) -> str | None:
    """Return source proposal text for a grading record using strict analysis_id linking."""
    direct_text = grading_record.get("input_text")
    if isinstance(direct_text, str) and direct_text.strip():
        return direct_text

    analysis_id = record_analysis_id(grading_record)
    if not analysis_id:
        return None

    index = analysis_index if analysis_index is not None else build_analysis_history_index()
    linked_record = index.get(analysis_id)
    if not isinstance(linked_record, dict):
        return None
    linked_text = linked_record.get("input_text")
    return linked_text if isinstance(linked_text, str) and linked_text.strip() else None


def delete_analysis_record_by_id(analysis_id: str) -> dict[str, Any]:
    """Delete one analysis history record by ID and return it."""
    normalized_id = analysis_id.strip()
    history = load_analysis_history()
    for index, record in enumerate(history):
        if isinstance(record, dict) and (
            record.get("analysis_id") == normalized_id
            or record.get("id") == normalized_id
        ):
            deleted = history.pop(index)
            write_analysis_history(history)
            return deleted
    raise HTTPException(
        status_code=status.HTTP_404_NOT_FOUND,
        detail="Analysis history record not found.",
    )


