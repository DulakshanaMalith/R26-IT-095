def stringify_report_item(value: Any) -> str:
    """Convert report payload values into compact readable text."""
    if value is None:
        return ""
    if isinstance(value, str):
        return value.strip()
    if isinstance(value, dict):
        preferred_parts = []
        for key in (
            "title",
            "category",
            "tag",
            "comment_text",
            "feedback",
            "annotated_text",
            "concept",
            "source",
            "target",
            "relation",
            "url",
        ):
            item = value.get(key)
            if item:
                preferred_parts.append(f"{key.replace('_', ' ').title()}: {item}")
        if preferred_parts:
            return "; ".join(preferred_parts)
        return json.dumps(value, ensure_ascii=False)
    return str(value).strip()


def paragraph_text(value: Any, fallback: str = "Not available.") -> str:
    """Return report-safe paragraph content without inventing data."""
    text = stringify_report_item(value)
    return text if text else fallback


def pdf_text(value: Any, fallback: str = "Not available.") -> str:
    """Escape dynamic text for ReportLab Paragraph rendering."""
    return escape(paragraph_text(value, fallback))


