def build_final_feedback_filename(
    *,
    student: dict[str, Any],
    proposal: dict[str, Any],
    version: dict[str, Any],
    analysis_id: str,
    generated_at: datetime,
) -> str:
    """Build a stable filename for supervisor-approved student feedback."""
    student_part = safe_filename_part(student.get("academic_student_id") or student.get("full_name") or "student")
    proposal_part = safe_filename_part(proposal.get("title") or "proposal")
    version_part = f"v{version.get('version_number') or 'current'}"
    analysis_part = safe_filename_part(analysis_id or generated_at.strftime("%Y%m%d"))
    return f"researchpilot-final-feedback-{student_part}-{proposal_part}-{version_part}-{analysis_part}.pdf"


