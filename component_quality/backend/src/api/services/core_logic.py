def build_action_plan_rows(payload: GenerateReportRequest) -> list[list[str]]:
    """Create deterministic action-plan rows from available report data only."""
    rows: list[tuple[str, list[str]]] = []
    resources = payload.recommendations if isinstance(payload.recommendations, list) else []
    feedback = payload.feedback if isinstance(payload.feedback, list) else []
    missing = payload.knowledge_graph.missing_concepts if payload.knowledge_graph else []
    section_scores = payload.semantic_grade.section_scores if payload.semantic_grade else {}

    def resource_title(topic: str = "", fallback_index: int = 0) -> str:
        topic_key = topic.lower()
        generic_terms = {
            "section", "score", "proposal", "research", "clearer", "evidence",
            "structure", "academic", "detail", "details", "needs", "missing",
            "concept", "improvement", "opportunity", "review", "resource",
        }
        topic_terms = [
            term.strip(".,:;()[]{}")
            for term in topic_key.split()
            if len(term.strip(".,:;()[]{}")) > 3 and term.strip(".,:;()[]{}") not in generic_terms
        ]
        for resource in resources:
            if not isinstance(resource, dict):
                continue
            haystack = " ".join(
                raw_text(resource.get(key), "", 100)
                for key in ("category", "topic", "title", "description")
            ).lower()
            if topic_key and (topic_key in haystack or any(term in haystack for term in topic_terms)):
                return raw_text(resource.get("title"), "Review recommended resources", 80)
        if resources and isinstance(resources[min(fallback_index, len(resources) - 1)], dict):
            return raw_text(resources[min(fallback_index, len(resources) - 1)].get("title"), "Review recommended resources", 80)
        return "Review recommended resources" if resources else "No specific resource available"

    def is_improvement_feedback(item: Any) -> bool:
        if isinstance(item, dict):
            tag = raw_text(item.get("tag"), "", 40).lower()
            comment = raw_text(item.get("comment_text") or item.get("feedback"), "", 200).lower()
        else:
            tag = ""
            comment = raw_text(item, "", 200).lower()
        issue_terms = ("weak", "unclear", "missing", "lack", "lacks", "insufficient", "needs", "problem", "not", "improve", "revise")
        if tag in {"strength", "highlight"} and not any(term in comment for term in issue_terms):
            return False
        if any(term in comment for term in issue_terms):
            return True
        return tag == "weakness"

    for section, score in list(section_scores.items())[:4]:
        try:
            percentage = float(score)
        except (TypeError, ValueError):
            continue
        if percentage < 65:
            rows.append(("High", [
                "High",
                f"{section} score is {format_score(percentage)}%.",
                f"Revise the {section.lower()} section with clearer evidence, structure, and academic detail.",
                resource_title(section, len(rows)),
            ]))

    for item in feedback:
        if not is_improvement_feedback(item):
            continue
        if isinstance(item, dict):
            issue = raw_text(item.get("comment_text") or item.get("feedback"), max_chars=120)
        else:
            issue = raw_text(item, max_chars=120)
        if issue and issue != "Not available.":
            rows.append(("Medium", ["Medium", issue, "Apply the mentor comment in the next proposal revision.", resource_title(issue, len(rows))]))

    for concept in missing[:3]:
        concept_text = raw_text(concept, max_chars=80)
        rows.append(("Medium", [
            "Medium",
            f"Missing concept: {concept_text}.",
            f"Add or clarify the role of {concept_text.lower()} in the proposal.",
            resource_title(concept_text, len(rows)),
        ]))

    priority_order = {"High": 0, "Medium": 1, "Low": 2}
    rows.sort(key=lambda item: priority_order.get(item[0], 99))
    return [row for _, row in rows[:8]]


