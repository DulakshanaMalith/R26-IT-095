def term_count(text: str, terms: list[str] | set[str]) -> int:
    """Count how many configured terms appear in text."""
    lowered = text.lower()
    return sum(1 for term in terms if re.search(rf"\b{re.escape(term.lower())}\b", lowered))


def has_citation(text: str) -> bool:
    """Detect simple citation/reference evidence."""
    return bool(
        re.search(r"\([A-Z][A-Za-z-]+,\s*\d{4}\)", text)
        or re.search(r"\[[0-9,\s]+\]", text)
        or re.search(r"\b(et al\.|references|bibliography)\b", text, re.IGNORECASE)
    )


def heading_pattern(headings: list[str]) -> re.Pattern[str]:
    """Build a multiline section heading detector."""
    alternatives = "|".join(re.escape(heading) for heading in headings)
    return re.compile(rf"(?im)^\s*(?:\d+(?:\.\d+)*\s*)?(?:{alternatives})\s*:?\s*$")


def extract_section_text(text: str, section_name: str) -> tuple[str, bool]:
    """Return section body text and whether a matching heading was found."""
    config = SECTION_CONFIG[section_name]
    matches = list(heading_pattern(config["headings"]).finditer(text))
    if not matches:
        return text, False

    section_start = matches[0].end()
    other_heading_patterns = []
    for name, other_config in SECTION_CONFIG.items():
        if name != section_name:
            other_heading_patterns.extend(other_config["headings"])
    next_heading = heading_pattern(other_heading_patterns).search(text, section_start)
    section_end = next_heading.start() if next_heading else len(text)
    section_text = text[section_start:section_end].strip()
    return section_text or text, True


def score_section(text: str, section_name: str) -> int:
    """Estimate one section score with transparent text heuristics."""
    config = SECTION_CONFIG[section_name]
    section_text, heading_found = extract_section_text(text, section_name)
    words = re.findall(r"\b\w+\b", section_text)
    word_count = len(words)

    score = 0
    if heading_found:
        score += 25

    min_words = int(config["min_words"])
    if word_count >= min_words:
        score += 25
    elif word_count >= min_words * 0.6:
        score += 18
    elif word_count >= min_words * 0.3:
        score += 10

    academic_hits = term_count(section_text, ACADEMIC_TERMS)
    score += min(20, academic_hits * 4)

    section_hits = term_count(section_text, config["terms"])
    score += min(20, section_hits * 4)

    if section_name == "Literature Review" and has_citation(section_text):
        score += 10
    elif section_name == "Innovation" and term_count(section_text, ["novel", "innovative", "original", "contribution"]):
        score += 10
    elif section_name == "Academic Writing":
        sentence_count = len(re.findall(r"[.!?]+", section_text))
        average_sentence_length = word_count / max(sentence_count, 1)
        if 12 <= average_sentence_length <= 32:
            score += 10
        elif word_count >= min_words:
            score += 5

    if not heading_found and section_hits == 0:
        score = min(score, 55)

    return max(0, min(100, int(round(score))))


def calculate_section_scores(text: str) -> dict[str, int]:
    """Calculate rule-based section-level scores for a graded proposal."""
    return {section_name: score_section(text, section_name) for section_name in SECTION_NAMES}


COMPLETENESS_SECTION_WEIGHTS = {
    "Abstract": 20,
    "Introduction": 15,
    "Research Gap": 15,
    "Objectives": 15,
    "Methodology": 20,
    "Literature Review": 10,
    "Evaluation": 5,
}

VALIDATOR_SECTION_LABELS = {
    "abstract": "Abstract",
    "introduction": "Introduction",
    "research_gap": "Research Gap",
    "objectives": "Objectives",
    "methodology": "Methodology",
    "literature_review": "Literature Review",
    "evaluation": "Evaluation",
}


def canonical_section_label(section: Any) -> str:
    """Convert validator section identifiers to display labels used by completeness weights."""
    text = str(section or "").strip()
    if not text:
        return ""
    normalized = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")
    return VALIDATOR_SECTION_LABELS.get(normalized, text.replace("_", " ").title())


def calculate_completeness_from_missing(missing_sections: list[Any]) -> tuple[float, dict[str, int], list[str]]:
    """Calculate proposal completeness directly from validator missing_sections."""
    canonical_missing: list[str] = []
    seen: set[str] = set()
    for section in missing_sections or []:
        label = canonical_section_label(section)
        if label in COMPLETENESS_SECTION_WEIGHTS and label not in seen:
            canonical_missing.append(label)
            seen.add(label)
    deductions = {
        section: COMPLETENESS_SECTION_WEIGHTS[section]
        for section in canonical_missing
    }
    return float(max(0, 100 - sum(deductions.values()))), deductions, canonical_missing


def analysis_tag_from_validation(model_tag: str, validation: Any) -> tuple[str, str]:
    """Combine raw SVM tag with structural proposal validation for user-facing analytics."""
    completeness, _, missing_sections = calculate_completeness_from_missing(validation.missing_sections)
    if missing_sections:
        return (
            "Weakness",
            (
                f"Structural proposal weakness detected: missing {', '.join(missing_sections)}. "
                f"Raw SVM annotation tag was {model_tag}."
            ),
        )
    if not validation.is_valid_proposal:
        return (
            "Weakness",
            f"Document validator rejected the text as a research proposal. Raw SVM annotation tag was {model_tag}.",
        )
    return model_tag, "Raw SVM annotation tag retained; proposal structure passed completeness checks."


def effective_analysis_record(record: dict[str, Any]) -> dict[str, Any]:
    """Return an analysis record with a validator-aware user-facing predicted_tag."""
    normalized = dict(record)
    raw_model_tag = str(record.get("model_predicted_tag") or record.get("predicted_tag") or "Other")
    text = record.get("input_text")
    if isinstance(text, str) and text.strip():
        validation = validate_proposal_document(text)
        effective_tag, reason = analysis_tag_from_validation(raw_model_tag, validation)
        normalized["predicted_tag"] = effective_tag
        normalized["model_predicted_tag"] = raw_model_tag
        normalized["classification_reason"] = reason
    else:
        normalized["model_predicted_tag"] = raw_model_tag
        normalized.setdefault("classification_reason", "No source text available for structural classification.")
    return normalized


def completeness_from_text(text: str, base_payload: Any = None) -> dict[str, Any] | None:
    """Rebuild completeness from validator output when source text is available."""
    if not isinstance(text, str) or not text.strip():
        return None
    validation = validate_proposal_document(text)
    detected = sorted(
        {
            canonical_section_label(section)
            for section in validation.detected_sections
            if canonical_section_label(section)
        }
    )
    completeness, deductions, missing_sections = calculate_completeness_from_missing(validation.missing_sections)
    readiness = readiness_for_completeness(completeness)
    normalized = dict(base_payload) if isinstance(base_payload, dict) else {}
    normalized.update(
        {
            "percentage": completeness,
            "detected_sections": detected,
            "missing_sections": missing_sections,
            "deductions": deductions,
            "validation_confidence": round(float(validation.confidence), 2),
            "warnings": list(validation.warnings),
            "status": readiness.status,
        }
    )
    return normalized


def normalize_completeness_payload(payload: Any, source_text: str | None = None) -> dict[str, Any] | None:
    """Normalize stored completeness and reject legacy 100% values without validator evidence."""
    rebuilt = completeness_from_text(source_text or "", payload)
    if rebuilt is not None:
        return rebuilt

    if not isinstance(payload, dict):
        return None

    if payload.get("validation_confidence") is None:
        return None

    normalized = dict(payload)
    missing = normalized.get("missing_sections") or []
    if missing:
        completeness, deductions, canonical_missing = calculate_completeness_from_missing(missing)
        normalized["percentage"] = completeness
        normalized["missing_sections"] = canonical_missing
        normalized["deductions"] = deductions
        normalized["status"] = readiness_for_completeness(completeness).status
    return normalized


