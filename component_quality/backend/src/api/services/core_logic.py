def escape_pdf_text(text: str) -> str:
    """Escape text for a simple PDF content stream."""
    return text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def wrap_report_line(line: str, width: int = 92) -> list[str]:
    """Wrap long PDF fallback lines to keep them readable."""
    words = re.sub(r"\s+", " ", line).strip().split(" ")
    if not words or words == [""]:
        return [""]
    wrapped: list[str] = []
    current = ""
    for word in words:
        candidate = f"{current} {word}".strip()
        if len(candidate) > width and current:
            wrapped.append(current)
            current = word
        else:
            current = candidate
    if current:
        wrapped.append(current)
    return wrapped


def write_basic_pdf(path: Path, lines: list[str]) -> None:
    """Write a minimal valid PDF when ReportLab is unavailable."""
    display_lines: list[str] = []
    for line in lines:
        display_lines.extend(wrap_report_line(line))

    content_lines = ["BT", "/F1 10 Tf", "50 790 Td", "14 TL"]
    for index, line in enumerate(display_lines[:52]):
        if index:
            content_lines.append("T*")
        content_lines.append(f"({escape_pdf_text(line)}) Tj")
    content_lines.append("ET")
    stream = "\n".join(content_lines).encode("latin-1", errors="replace")

    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Length " + str(len(stream)).encode("ascii") + b" >>\nstream\n" + stream + b"\nendstream",
    ]

    pdf = bytearray(b"%PDF-1.4\n")
    offsets = [0]
    for number, obj in enumerate(objects, start=1):
        offsets.append(len(pdf))
        pdf.extend(f"{number} 0 obj\n".encode("ascii"))
        pdf.extend(obj)
        pdf.extend(b"\nendobj\n")
    xref_start = len(pdf)
    pdf.extend(f"xref\n0 {len(objects) + 1}\n".encode("ascii"))
    pdf.extend(b"0000000000 65535 f \n")
    for offset in offsets[1:]:
        pdf.extend(f"{offset:010d} 00000 n \n".encode("ascii"))
    pdf.extend(
        (
            f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\n"
            f"startxref\n{xref_start}\n%%EOF\n"
        ).encode("ascii")
    )
    path.write_bytes(pdf)


def safe_text(value: Any, fallback: str = "Not available.", max_chars: int | None = None) -> str:
    """Return escaped, compact text for ReportLab Paragraph content."""
    text = paragraph_text(value, fallback)
    text = re.sub(r"\s+", " ", text).strip()
    if max_chars and len(text) > max_chars:
        text = text[:max_chars].rsplit(" ", 1)[0].strip() + "..."
    return escape(text or fallback)


def raw_text(value: Any, fallback: str = "Not available.", max_chars: int | None = None) -> str:
    """Return compact unescaped text for filenames and plain metadata."""
    text = paragraph_text(value, fallback)
    text = re.sub(r"\s+", " ", text).strip()
    if max_chars and len(text) > max_chars:
        text = text[:max_chars].rsplit(" ", 1)[0].strip() + "..."
    return text or fallback


def readable_report_datetime(value: Any, fallback: str = "Not available.") -> str:
    """Format ISO-like timestamps for student-facing reports."""
    if isinstance(value, datetime):
        parsed = value
    else:
        text = raw_text(value, "", 80)
        if not text:
            return fallback
        try:
            parsed = datetime.fromisoformat(text.replace("Z", "+00:00"))
        except ValueError:
            return text
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed.astimezone(timezone.utc).strftime("%d %b %Y, %I:%M %p UTC")


def safe_filename_part(value: Any) -> str:
    """Sanitize user-facing filenames for Windows and Linux."""
    text = raw_text(value, "analysis", 80)
    text = re.sub(r"[^\w.\-]+", "_", text, flags=re.ASCII).strip("._")
    return text or "analysis"


def clamp_score(value: Any, maximum: float = GRADING_MAX_SCORE) -> float | None:
    """Clamp numeric score values to the allowed grading range."""
    try:
        score = float(value)
    except (TypeError, ValueError):
        return None
    return max(0.0, min(maximum, score))


def score_level(percentage: float | None) -> str:
    """Return a readable performance level for a percentage."""
    if percentage is None:
        return "Not available"
    if percentage >= 80:
        return "Excellent"
    if percentage >= 65:
        return "Good"
    if percentage >= 50:
        return "Adequate"
    return "Needs Improvement"


def format_score(value: Any, decimals: int = 1) -> str:
    """Format score-like values consistently."""
    try:
        number = float(value)
    except (TypeError, ValueError):
        return "Not available"
    return f"{number:.{decimals}f}".rstrip("0").rstrip(".")


def graph_edge_text(edge: Any) -> str:
    """Render a graph edge as readable text."""
    if isinstance(edge, dict):
        source = raw_text(edge.get("source"), "Unknown source", 80)
        target = raw_text(edge.get("target"), "Unknown target", 80)
        relation = raw_text(edge.get("relation") or edge.get("label"), "related to", 40)
        weight = edge.get("weight")
        suffix = f" (weight {format_score(weight)})" if weight is not None else ""
        return f"{source} -> {relation} -> {target}{suffix}"
    return raw_text(edge, max_chars=160)


