def readiness_for_completeness(percentage: float) -> SubmissionReadinessPayload:
    """Map proposal completeness percentage to supervisor readiness."""
    if percentage >= 95:
        return SubmissionReadinessPayload(
            status="Ready for Supervisor Review",
            reason="All or nearly all essential proposal sections are present.",
            recommendation="Proceed to supervisor review while refining academic detail.",
        )
    if percentage >= 80:
        return SubmissionReadinessPayload(
            status="Minor Revision Required",
            reason="Most essential proposal sections are present, but some academic structure is incomplete.",
            recommendation="Address the missing or weak proposal sections before final submission.",
        )
    if percentage >= 60:
        return SubmissionReadinessPayload(
            status="Needs Revision",
            reason="Essential proposal sections are missing.",
            recommendation="Revise the proposal structure before relying on the semantic quality estimate.",
        )
    return SubmissionReadinessPayload(
        status="Incomplete Proposal",
        reason="Several essential proposal sections are missing.",
        recommendation="Rebuild the proposal with the required academic sections before supervisor review.",
    )


def build_final_proposal_assessment(
    text: str,
    predicted_score: float,
    percentage_score: float,
    label: str,
) -> dict[str, Any]:
    """Build the non-ML academic completeness/readiness layer."""
    validation = validate_proposal_document(text)
    detected = sorted(
        {
            canonical_section_label(section)
            for section in validation.detected_sections
            if canonical_section_label(section)
        }
    )
    completeness, deductions, missing_sections = calculate_completeness_from_missing(validation.missing_sections)
    readiness = readiness_for_completeness(completeness)
    final_readiness = calculate_final_readiness(percentage_score, completeness)
    completeness_payload = ProposalCompletenessPayload(
        percentage=completeness,
        detected_sections=detected,
        missing_sections=missing_sections,
        deductions=deductions,
        validation_confidence=round(float(validation.confidence), 2),
        warnings=list(validation.warnings),
        status=readiness.status,
    )
    final_payload = FinalProposalAssessmentPayload(
        semantic_grade={
            "score": predicted_score,
            "percentage": percentage_score,
            "label": label,
        },
        proposal_completeness=completeness_payload,
        submission_readiness=readiness,
        final_readiness=FinalReadinessPayload(**final_readiness) if final_readiness else None,
    )
    return {
        "proposal_completeness": completeness_payload.model_dump(),
        "submission_readiness": readiness.model_dump(),
        "final_readiness": final_readiness,
        "final_proposal_assessment": final_payload.model_dump(),
    }


