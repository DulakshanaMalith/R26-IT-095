def resolve_report_payload_from_history(payload: GenerateReportRequest) -> GenerateReportRequest:
    """Merge report payload with saved analysis metadata, preserving legacy history."""
    record = find_analysis_record_by_id(payload.analysis_id)
    linked_graph = find_graph_record_by_analysis_id(payload.analysis_id)
    linked_grade = find_grading_record_by_analysis_id(payload.analysis_id)
    if not record and not linked_graph and not linked_grade:
        return payload

    def saved_or_payload(saved_key: str, current_value: Any) -> Any:
        saved_value = record.get(saved_key)
        return saved_value if saved_value not in (None, "") else current_value

    def saved_identity(saved_key: str) -> Any:
        saved_value = record.get(saved_key)
        return saved_value if saved_value not in (None, "") else None

    updates = {}
    if record:
        record = effective_analysis_record(record)
        updates.update({
        "student_name": saved_identity("student_name"),
        "student_id": saved_identity("student_id"),
        "proposal_title": saved_or_payload("proposal_title", payload.proposal_title),
        "filename": saved_or_payload("filename", payload.filename),
        "source": saved_or_payload("source", payload.source),
        "analysis_timestamp": record.get("timestamp") or payload.analysis_timestamp,
        "input_text": record.get("input_text") or payload.input_text,
        "predicted_tag": record.get("predicted_tag") or payload.predicted_tag,
        "feedback": record.get("retrieved_feedback") or payload.feedback,
        "recommendations": record.get("recommended_resources") or payload.recommendations,
        })
    if linked_graph and not (
        payload.knowledge_graph.concepts
        or payload.knowledge_graph.edges
        or payload.knowledge_graph.missing_concepts
    ):
        updates["knowledge_graph"] = KnowledgeGraphPayload(
            concepts=linked_graph.get("concepts", []),
            edges=linked_graph.get("edges", []),
            missing_concepts=linked_graph.get("missing_concepts", []),
        )
    if linked_grade and payload.semantic_grade is None:
        linked_percentage = linked_grade.get("percentage_score")
        updates["semantic_grade"] = SemanticGradePayload(
            predicted_score=linked_grade.get("predicted_score"),
            max_score=linked_grade.get("max_score"),
            percentage_score=linked_percentage,
            score_label=normalized_semantic_label(linked_percentage, linked_grade.get("score_label")),
            section_scores=linked_grade.get("section_scores") or {},
            model_status=linked_grade.get("model_status"),
            warning=linked_grade.get("warning"),
        )
    if linked_grade and payload.proposal_completeness is None and linked_grade.get("proposal_completeness"):
        normalized_completeness = normalize_completeness_payload(
            linked_grade["proposal_completeness"],
            linked_grade.get("input_text") or updates.get("input_text") or payload.input_text,
        )
        if normalized_completeness:
            updates["proposal_completeness"] = ProposalCompletenessPayload(**normalized_completeness)
    if linked_grade and payload.submission_readiness is None:
        if updates.get("proposal_completeness"):
            percentage = float(updates["proposal_completeness"].percentage or 0)
            updates["submission_readiness"] = readiness_for_completeness(percentage)
        elif linked_grade.get("submission_readiness") and linked_grade.get("input_text"):
            updates["submission_readiness"] = SubmissionReadinessPayload(**linked_grade["submission_readiness"])
    if linked_grade and payload.final_proposal_assessment is None and updates.get("proposal_completeness"):
        final_readiness = normalize_final_readiness_payload(
            linked_grade,
            linked_grade.get("percentage_score"),
            updates["proposal_completeness"].model_dump(),
        )
        if final_readiness:
            updates["final_readiness"] = FinalReadinessPayload(**final_readiness)
            updates["final_readiness_percentage"] = final_readiness.get("percentage")
            updates["final_readiness_label"] = final_readiness.get("label")
        readiness_payload = updates.get("submission_readiness")
        if readiness_payload is None:
            readiness_payload = readiness_for_completeness(float(updates["proposal_completeness"].percentage or 0))
        updates["final_proposal_assessment"] = FinalProposalAssessmentPayload(
            semantic_grade={
                "score": linked_grade.get("predicted_score"),
                "percentage": linked_grade.get("percentage_score"),
                "label": normalized_semantic_label(
                    linked_grade.get("percentage_score"),
                    linked_grade.get("score_label"),
                ),
            },
            proposal_completeness=updates["proposal_completeness"],
            submission_readiness=readiness_payload,
            final_readiness=updates.get("final_readiness"),
        )
    return payload.model_copy(update=updates)


def percentage_from_score(score: float) -> float:
    """Convert the baseline 0-42 score into a percentage."""
    clamped_score = max(0.0, min(float(GRADING_MAX_SCORE), float(score)))
    return round((clamped_score / GRADING_MAX_SCORE) * 100, 1)


def score_label(percentage_score: float) -> str:
    """Backward-compatible alias for the calibrated semantic label helper."""
    return get_semantic_label(percentage_score)


def get_semantic_label(semantic_percentage: Any) -> str:
    """Return a conservative display label for the AI semantic estimate."""
    try:
        percentage = max(0.0, min(100.0, float(semantic_percentage)))
    except (TypeError, ValueError):
        return "Not available"
    if percentage >= 90:
        return "Very Strong"
    if percentage >= 80:
        return "Strong"
    if percentage >= 70:
        return "Moderate"
    if percentage >= 60:
        return "Developing"
    return "Limited Semantic Evidence"


def normalized_semantic_label(percentage_score: Any, fallback: Any = None) -> str | None:
    """Derive the current semantic display label from the numeric percentage."""
    if percentage_score is not None:
        return get_semantic_label(percentage_score)
    return str(fallback) if fallback not in (None, "") else None


